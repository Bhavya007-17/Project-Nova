"""`nova bench-llm --runtime` (Stage 07a): the pure parts of the Ollama vs llama-server comparison."""

from pathlib import Path

from nova import cli
from nova.bench_llm import ADOPT_GAIN, Timing, gain, gguf_path, runtime_row, server_args, server_env

MODELFILE = """# Modelfile generated by "ollama show"
# FROM qwen3.5:4b

FROM C:\\Users\\me\\.ollama\\models\\blobs\\sha256-aaa
FROM C:\\Users\\me\\.ollama\\models\\blobs\\sha256-bbb
TEMPLATE {{ .Prompt }}
PARAMETER temperature 1
"""


def test_the_gguf_is_the_first_from_path_and_the_second_is_the_vision_projector():
    assert gguf_path(MODELFILE) == "C:\\Users\\me\\.ollama\\models\\blobs\\sha256-aaa"
    assert gguf_path("FROM qwen3.5:4b\n") is None  # a model name, not a file
    assert gguf_path("") is None


def test_server_runs_the_same_model_without_the_projector_on_loopback():
    args = server_args(Path("C:/o/llama-server.exe"), "C:/blobs/sha256-aaa", port=8091)
    assert args[0].endswith("llama-server.exe")
    joined = " ".join(args)
    assert "-m C:/blobs/sha256-aaa" in joined and "--host 127.0.0.1" in joined and "--port 8091" in joined
    assert "-c 4096" in joined and "-np 1" in joined and "-ngl 99" in joined
    assert "--mmproj" not in joined  # no vision model in v1


def test_server_env_puts_the_cuda_backend_on_the_dll_path():
    env = server_env(Path("C:/o"), {"PATH": "C:/Windows"})
    assert env["PATH"].split(";")[0].replace("\\", "/") == "C:/o/cuda_v13"
    assert env["GGML_BACKEND_PATH"].replace("\\", "/") == "C:/o/cuda_v13/ggml-cuda.dll"


def test_runtime_row_percentiles_overhead_and_speed():
    timings = [Timing(ms=1000 + i * 10, prompt_ms=70, eval_ms=400, tokens=26, prompt_tokens=50, json_ok=i != 0)
               for i in range(21)]
    row = runtime_row("ollama", "schema", timings, cold_ms=9000)
    assert row.n == 21 and row.p50 == 1100 and row.p95 == 1190
    assert row.overhead_p50 == 1100 - 70 - 400 and row.tps_p50 == 65.0 and row.not_json == 1 and row.cold_ms == 9000


def test_adopt_only_when_warm_p50_is_at_least_30_percent_better():
    assert ADOPT_GAIN == 0.30
    assert gain(744.0, 524.0) < ADOPT_GAIN  # 2026-11-12: 29.6 % -> not adopted
    assert gain(1000.0, 700.0) >= ADOPT_GAIN
    assert gain(0.0, 500.0) == 0.0


def test_cli_runtime_flag_dispatches(monkeypatch):
    seen = []
    monkeypatch.setattr("nova.bench_llm.runtimes", lambda names, **kw: seen.append((names, kw)) or 0)
    assert cli.main(["bench-llm", "--runtime", "ollama,llama-server", "--cases", "12", "--rounds", "1"]) == 0
    assert seen == [(("ollama", "llama-server"), {"cases": 12, "rounds": 1})]
